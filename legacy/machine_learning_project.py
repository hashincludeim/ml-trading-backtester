"""### RSI
- This indicator measures the strength of a stock's price action relative to its previous price action. The RSI ranges from 0 to 100, with readings above 70 indicating overbought conditions and readings below 30 indicating oversold conditions.
"""

# Calculate RSI
def calculate_rsi(data, n=14):
    delta = data['Close'].diff()
    up = delta.where(delta > 0, 0)
    down = -delta.where(delta < 0, 0)
    ema_up = up.ewm(com=n - 1, min_periods=n).mean()
    ema_down = down.ewm(com=n - 1, min_periods=n).mean()
    rs = ema_up / ema_down
    return pd.Series(100 - (100 / (1 + rs)))

