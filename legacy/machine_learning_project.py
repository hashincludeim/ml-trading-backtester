import numpy as np

def sharpe_ratio(returns, risk_free_rate=0.0):
    excess_returns = returns - risk_free_rate
    return np.mean(excess_returns) / np.std(excess_returns)

def sortino_ratio(returns, risk_free_rate=0.0, target_return=0.0):
    excess_returns = returns - risk_free_rate
    downside_returns = excess_returns.copy()
    downside_returns[excess_returns > target_return] = 0.0
    return np.mean(excess_returns) / np.std(downside_returns)

def calmar_ratio(returns, max_drawdown):
    return np.mean(returns) / max_drawdown

# Calculate risk-adjusted performance metrics
risk_free_rate = 0.0
market_returns = trade_dataset['Tomorrows Returns']
strategy_returns = trade_dataset['Strategy Returns']

sharpe_market = sharpe_ratio(market_returns, risk_free_rate)
sharpe_strategy = sharpe_ratio(strategy_returns, risk_free_rate)

sortino_market = sortino_ratio(market_returns, risk_free_rate)
sortino_strategy = sortino_ratio(strategy_returns, risk_free_rate)

# Calculate the maximum drawdown for the market and the strategy
cumulative_market_returns = trade_dataset['Cumulative Market Returns']
cumulative_strategy_returns = trade_dataset['Cumulative Strategy Returns']

max_dd_market = np.max(np.maximum.accumulate(cumulative_market_returns) - cumulative_market_returns)
max_dd_strategy = np.max(np.maximum.accumulate(cumulative_strategy_returns) - cumulative_strategy_returns)

calmar_market = calmar_ratio(market_returns, max_dd_market)
calmar_strategy = calmar_ratio(strategy_returns, max_dd_strategy)

